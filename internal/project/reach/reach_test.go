package reach

import (
	"reflect"
	"testing"
)

func program() []File {
	return []File{
		{Path: "go.mod", Content: []byte("module example.test/app\n")},
		{Path: "main.go", Content: []byte(`package main

import "example.test/app/cmd"

func main() { cmd.Execute() }
`)},
		{Path: "cmd/root.go", Content: []byte(`package cmd

// rootCmd runs run: a command table is package-level code.
var rootCmd = command{Run: run}

type command struct{ Run func() }

type saver interface{ save() }

func Execute() { rootCmd.Run() }

func run() { helper(); var s store; use(s) }

func helper() {}

func use(s saver) { s.save() }

type store struct{}

// save is called through the saver interface.
func (store) save() {}

// Lost is exported, but this module is a program, not a library.
func Lost() { deeper() }

func deeper() {}

func onlyTests() {}

func init() { registered() }

func registered() {}

//export exported
func exported() {}

func (store) String() string { return "store" }

func byName() {}

var lookup = "byName"
`)},
		{Path: "cmd/root_test.go", Test: true, Content: []byte(`package cmd

import "testing"

func TestOnly(t *testing.T) { onlyTests() }
`)},
	}
}

func TestFindReportsWhatNoEntryPointReaches(t *testing.T) {
	got := Find(program())
	want := []Unused{
		{Path: "cmd/root.go", Function: "Lost", StartLine: 24, EndLine: 24},
		{Path: "cmd/root.go", Function: "deeper", StartLine: 26, EndLine: 26},
		{Path: "cmd/root.go", Function: "onlyTests", StartLine: 28, EndLine: 28, TestOnly: true},
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("unused = %+v\nwant %+v", got, want)
	}
}

func TestALibrarysExportedCodeIsItsAPI(t *testing.T) {
	files := []File{
		{Path: "go.mod", Content: []byte("module example.test/lib\n")},
		{Path: "lib.go", Content: []byte("package lib\n\nfunc Public() { inner() }\n\nfunc inner() {}\n\nfunc dead() {}\n")},
	}
	if got := Find(files); len(got) != 1 || got[0].Function != "dead" {
		t.Fatalf("unused = %+v", got)
	}
}

func TestNestedModulesAreJudgedOnTheirOwn(t *testing.T) {
	files := append(program(),
		File{Path: "desktop/go.mod", Content: []byte("module example.test/desktop\n")},
		File{Path: "desktop/api.go", Content: []byte("package desktop\n\nfunc Open() {}\n")},
		File{Path: "vendor/x/x.go", Content: []byte("package x\n\nfunc vendored() {}\n")},
		File{Path: "broken.go", Content: []byte("package main\n\nfunc (\n")},
		File{Path: "gen.go", Content: []byte("// Code generated by tool. DO NOT EDIT.\n\npackage main\n\nfunc generated() {}\n")},
	)
	for _, unused := range Find(files) {
		switch unused.Function {
		case "Open", "vendored", "generated":
			t.Fatalf("%s was reported unused: %+v", unused.Function, unused)
		}
	}
}

func TestAMethodIsNamedWithItsType(t *testing.T) {
	files := []File{{Path: "main.go", Content: []byte("package main\n\ntype T[K any] struct{}\n\nfunc main() {}\n\nfunc (t *T[K]) unused() {}\n")}}
	if got := Find(files); len(got) != 1 || got[0].Function != "T.unused" {
		t.Fatalf("unused = %+v", got)
	}
}

func TestAMainPackageWithoutMainHasNoUnusedCode(t *testing.T) {
	files := []File{{Path: "tool/run.go", Content: []byte("package main\n\nfunc Run() {}\n\nfunc helper() {}\n")}}
	if got := Find(files); len(got) != 0 {
		t.Fatalf("unused = %+v", got)
	}
}
