package dupes

import (
	"strings"
	"testing"
)

const block = `	value, err := strconv.Atoi(input)
	if err != nil {
		return fmt.Errorf("parse count %q: %w", input, err)
	}
	if value < minimumCount || value > maximumCount {
		return fmt.Errorf("count %d out of range", value)
	}
	total += value
	seen[input] = true
`

func TestFindReportsABlockRepeatedInTwoFilesWithItsLines(t *testing.T) {
	first := "package a\n\nfunc one() error {\n" + block + "\treturn nil\n}\n"
	second := "package b\n\n// two parses too.\nfunc two() error {\n\tlog.Println(\"two\")\n" + block + "\treturn save()\n}\n"
	report := Find([]File{{Path: "a.go", Content: first}, {Path: "b.go", Content: second}})
	if len(report.Groups) != 1 {
		t.Fatalf("groups = %+v", report.Groups)
	}
	group := report.Groups[0]
	if group.Lines != 7 || len(group.Places) != 2 || group.Places[0] != (Place{Path: "a.go", StartLine: 4, EndLine: 12}) || group.Places[1] != (Place{Path: "b.go", StartLine: 6, EndLine: 14}) {
		t.Fatalf("group = %+v", group)
	}
	if !strings.HasPrefix(group.Preview, "value, err := strconv.Atoi") || report.RepeatedLines != 7 || report.TotalLines == 0 {
		t.Fatalf("report = %+v", report)
	}
}

func TestFindGroupsThreeCopiesAndIgnoresShortOrPunctuationOnlyRepeats(t *testing.T) {
	short := "\tif err != nil {\n\t\treturn err\n\t}\n"
	files := []File{
		{Path: "a.go", Content: "func a() {\n" + block + short + "}\n"},
		{Path: "b.go", Content: "func b() {\n" + block + "}\n"},
		{Path: "c.go", Content: "func c() {\n" + short + block + "}\n"},
		{Path: "d.go", Content: "func d() {\n" + short + "\t}\n\t}\n\t)\n}\n"},
	}
	report := Find(files)
	if len(report.Groups) != 1 || len(report.Groups[0].Places) != 3 || report.RepeatedLines != 14 {
		t.Fatalf("report = %+v", report)
	}
}

func TestFindSkipsGeneratedFiles(t *testing.T) {
	generated := "// Code generated by tool. DO NOT EDIT.\n" + block
	if report := Find([]File{{Path: "a.go", Content: block}, {Path: "a_gen.go", Content: generated}}); len(report.Groups) != 0 {
		t.Fatalf("groups = %+v", report.Groups)
	}
}
